import type { ReactNode } from 'react'

type IconButtonProps = {
  label: string
  onClick: () => void
  disabled?: boolean
  active?: boolean
  variant?: 'default' | 'danger' | 'success'
  children: ReactNode
}

const variantClass = {
  default:
    'border-white/15 text-slate-300 hover:border-flowop-green/50 hover:text-white',
  danger: 'border-white/10 text-red-300 hover:border-red-400/40 hover:text-red-200',
  success:
    'border-white/15 text-emerald-300 hover:border-emerald-400/40 hover:text-emerald-200',
}

export function FollowUpActionIconButton({
  label,
  onClick,
  disabled = false,
  active = false,
  variant = 'default',
  children,
}: IconButtonProps) {
  return (
    <button
      type="button"
      title={label}
      aria-label={label}
      disabled={disabled}
      onClick={onClick}
      className={[
        'relative inline-flex h-7 w-7 shrink-0 items-center justify-center rounded border transition-colors disabled:cursor-not-allowed disabled:opacity-40',
        active
          ? 'border-flowop-green/50 bg-flowop-green/15 text-white'
          : variantClass[variant],
      ].join(' ')}
    >
      {children}
    </button>
  )
}

